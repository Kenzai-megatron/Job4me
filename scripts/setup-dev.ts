import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { ENV_FILE } from './lib';

// `pnpm setup:dev`: writes a local .env with throwaway secrets (never committed).

function password(): string {
  return randomBytes(24).toString('base64url');
}

/** VAPID key pair for Web Push: P-256, public key as an uncompressed point. */
function vapidKeys(): { publicKey: string; privateKey: string } {
  const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
  const pub = publicKey.export({ format: 'jwk' });
  const priv = privateKey.export({ format: 'jwk' });
  if (!pub.x || !pub.y || !priv.d) throw new Error('unexpected key format');
  const point = Buffer.concat([
    Buffer.from([4]),
    Buffer.from(pub.x, 'base64url'),
    Buffer.from(pub.y, 'base64url'),
  ]);
  return { publicKey: point.toString('base64url'), privateKey: priv.d };
}

const force = process.argv.includes('--force');
if (existsSync(ENV_FILE) && !force) {
  console.log('.env already exists: nothing to do (use --force to replace it).');
  process.exit(0);
}

const ownerPassword = password();
const appPassword = password();
const vapid = vapidKeys();
const lines = [
  '# Generated by `pnpm setup:dev`. Local development only; never commit this file.',
  'JOB4ME_ENV=development',
  `JOB4ME_DB_OWNER_PASSWORD=${ownerPassword}`,
  `JOB4ME_DATABASE_OWNER_URL=postgres://job4me_owner:${ownerPassword}@127.0.0.1:5432/job4me`,
  `JOB4ME_DATABASE_URL=postgres://job4me_app:${appPassword}@127.0.0.1:5432/job4me`,
  `JOB4ME_MASTER_KEY=${randomBytes(32).toString('base64')}`,
  `JOB4ME_VAPID_PUBLIC_KEY=${vapid.publicKey}`,
  `JOB4ME_VAPID_PRIVATE_KEY=${vapid.privateKey}`,
  '',
];
writeFileSync(ENV_FILE, lines.join('\n'), { mode: 0o600 });
console.log('.env written with fresh development secrets.');
