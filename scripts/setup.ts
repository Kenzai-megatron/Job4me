import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { appendFileSync, chmodSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { ENV_FILE, readEnvFile, ROOT } from './lib';

// `pnpm setup:dev` and `pnpm setup:home`: secrets as files in secrets/ (never committed, read
// through *_FILE variables), and a .env that only holds settings and the paths to those files.
// Run again after an update: missing secrets and settings are added, existing ones are kept.

const SECRETS_DIR = join(ROOT, 'secrets');
/** Files volume: imported files (ADR 0010), later the generated documents. */
const FILES_DIR = join(ROOT, 'var', 'files');

function vapidKeys(): { publicKey: string; privateKey: string } {
  const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
  const pub = publicKey.export({ format: 'jwk' });
  const priv = privateKey.export({ format: 'jwk' });
  if (!pub.x || !pub.y || !priv.d) throw new Error('unexpected key format');
  const point = Buffer.concat([
    Buffer.from([4]),
    Buffer.from(pub.x, 'base64url'),
    Buffer.from(pub.y, 'base64url'),
  ]);
  return { publicKey: point.toString('base64url'), privateKey: priv.d };
}

/** Writes each secret once; existing files are kept so a rerun never breaks a database. */
function ensureSecrets(): Record<string, string> {
  mkdirSync(SECRETS_DIR, { recursive: true, mode: 0o700 });
  chmodSync(SECRETS_DIR, 0o700);
  const vapid = vapidKeys();
  const values: Record<string, () => string> = {
    db_owner_password: () => randomBytes(24).toString('base64url'),
    db_app_password: () => randomBytes(24).toString('base64url'),
    master_key: () => randomBytes(32).toString('base64'),
    // Isolated extractor (ADR 0010): its own database role and a key apart from the master key.
    db_extractor_password: () => randomBytes(24).toString('base64url'),
    import_key: () => randomBytes(32).toString('base64'),
    // Left empty: the Claude API key is written by hand on the home machine (ADR 0009).
    anthropic_api_key: () => '',
    // Left empty too: the keys of Adzuna and SerpApi, later (ADR 0014, decision D2).
    adzuna_app_id: () => '',
    adzuna_app_key: () => '',
    serpapi_key: () => '',
    vapid_public_key: () => vapid.publicKey,
    vapid_private_key: () => vapid.privateKey,
  };
  const paths: Record<string, string> = {};
  for (const [name, generate] of Object.entries(values)) {
    const file = join(SECRETS_DIR, name);
    if (!existsSync(file)) {
      const value = generate();
      writeFileSync(file, value === '' ? '' : `${value}\n`, { mode: 0o600 });
      console.log(`secrets/${name} created${value === '' ? ' (empty)' : ''}.`);
    }
    paths[name] = file;
  }
  if (
    existsSync(join(SECRETS_DIR, 'vapid_public_key')) !==
    existsSync(join(SECRETS_DIR, 'vapid_private_key'))
  ) {
    throw new Error('secrets/vapid_public_key and vapid_private_key must exist together');
  }
  return paths;
}

const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: {
    force: { type: 'boolean', default: false },
    origin: { type: 'string' },
    contact: { type: 'string' },
  },
});
const mode = positionals[0];
if (mode !== 'dev' && mode !== 'home') {
  console.error('Usage: tsx scripts/setup.ts dev | home --origin https://job4me.<tailnet>.ts.net');
  process.exit(1);
}
if (mode === 'home' && process.getuid?.() === 0) {
  // The containers run as the owner of secrets/: run this as your usual user, not with sudo.
  console.error('Run setup:home as your usual user (in the docker group), not as root.');
  process.exit(1);
}
const secrets = ensureSecrets();
mkdirSync(join(FILES_DIR, 'imports'), { recursive: true, mode: 0o700 });
chmodSync(FILES_DIR, 0o700);
const lines = [
  `# Generated by \`pnpm setup:${mode}\`. Settings and paths only: secrets stay in secrets/.`,
  `JOB4ME_ENV=${mode === 'dev' ? 'development' : 'production'}`,
  `JOB4ME_SECRETS_DIR=${SECRETS_DIR}`,
  'JOB4ME_DB_HOST=127.0.0.1',
  // Containers run as the owner of secrets/, so the files can stay readable by that user only.
  `JOB4ME_UID=${process.getuid?.() ?? 1000}`,
  `JOB4ME_GID=${process.getgid?.() ?? 1000}`,
  `JOB4ME_DB_OWNER_PASSWORD_FILE=${secrets.db_owner_password}`,
  `JOB4ME_DB_APP_PASSWORD_FILE=${secrets.db_app_password}`,
  `JOB4ME_DB_EXTRACTOR_PASSWORD_FILE=${secrets.db_extractor_password}`,
  `JOB4ME_MASTER_KEY_FILE=${secrets.master_key}`,
  `JOB4ME_IMPORT_KEY_FILE=${secrets.import_key}`,
  `JOB4ME_ANTHROPIC_API_KEY_FILE=${secrets.anthropic_api_key}`,
  `JOB4ME_ADZUNA_APP_ID_FILE=${secrets.adzuna_app_id}`,
  `JOB4ME_ADZUNA_APP_KEY_FILE=${secrets.adzuna_app_key}`,
  `JOB4ME_SERPAPI_KEY_FILE=${secrets.serpapi_key}`,
  `JOB4ME_FILES_DIR=${FILES_DIR}`,
  `JOB4ME_VAPID_PUBLIC_KEY_FILE=${secrets.vapid_public_key}`,
  `JOB4ME_VAPID_PRIVATE_KEY_FILE=${secrets.vapid_private_key}`,
  // The demo source of the collection (no request at all): development only.
  ...(mode === 'dev' ? ['JOB4ME_COLLECT_DEMO_SOURCE=true'] : []),
];

const rewrite = !existsSync(ENV_FILE) || values.force;
if (mode === 'home' && (values.origin || rewrite)) {
  // A first run needs the address; a rerun after an update keeps the one already in .env.
  if (!values.origin) {
    console.error('setup:home needs --origin, e.g. --origin https://job4me.tail1234.ts.net');
    process.exit(1);
  }
  const origin = new URL(values.origin);
  if (origin.protocol !== 'https:' || origin.pathname !== '/') {
    console.error('--origin must be an https address without path, as Tailscale serves it');
    process.exit(1);
  }
  lines.push(`JOB4ME_PUBLIC_ORIGIN=${origin.origin}`, `JOB4ME_RP_ID=${origin.hostname}`);
  if (values.contact) lines.push(`JOB4ME_PUSH_CONTACT=${values.contact}`);
}

if (!rewrite) {
  // Keep every existing value; only add the settings a newer version needs.
  const existing = readEnvFile();
  const missing = lines.filter((line) => {
    const name = /^([A-Z0-9_]+)=/.exec(line)?.[1];
    return name !== undefined && !(name in existing);
  });
  if (missing.length === 0) {
    console.log('.env is up to date (use --force to rewrite it; secrets are kept).');
  } else {
    appendFileSync(ENV_FILE, `${missing.join('\n')}\n`);
    for (const line of missing) console.log(`.env: ${line.split('=')[0]} added.`);
  }
} else {
  writeFileSync(ENV_FILE, `${lines.join('\n')}\n`, { mode: 0o600 });
  console.log(`.env written for ${mode === 'dev' ? 'development' : 'the home machine'}.`);
}
